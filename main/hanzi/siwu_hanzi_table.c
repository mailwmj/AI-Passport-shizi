uint16_t siwu_hanzi_book_start(uint8_t book)
{
    if (book < 1 || book > SIWU_BOOK_COUNT) return 0;
    uint16_t start = 0;
    for (uint8_t b = 1; b < book; ++b) start = (uint16_t)(start + g_siwu_book_counts[b - 1]);
    return start;
}
